/**
 * The Zune layout's ground: the wallpaper, as the other layouts have, or the warm blur of colour
 * the Zune HD and its software were known by.
 */
enum class ZuneGlow {
    /** The wallpaper, as before. */
    OFF,

    /** Magenta running into orange, the Zune's own. */
    ZUNE,

    /** The same light in the launcher's accent colour. */
    ACCENT
}
